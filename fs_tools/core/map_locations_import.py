"""Copy the named places of the map of each hex from the game into the application.

fs-assets extracts them from the game files, so a new game version only needs a new
extraction and another import, whose result is reviewed and committed. The places go
into a Python module, so they travel inside the application with no file to load.
"""

import json
from pathlib import Path

from foxhole_stockpiles.enums.hex import Hex
from fs_tools.models.map_location_entry import MapLocationEntry
from fs_tools.models.map_locations import MapLocations
from fs_tools.models.map_locations_report import MapLocationsReport

_HEADER = '''"""The named places of the map of each hex, as the game places them.

Generated by ``fs-tools import-map-locations`` from what fs-assets extracts from the
game: do not edit it by hand.
"""

from typing import Final

type Location = tuple[str, float, float]
"""The name of a place and its coordinates on the map of its hex."""

LOCATIONS: Final[dict[str, tuple[Location, ...]]] = {
'''


def read_locations(path: Path) -> dict[str, list[MapLocationEntry]]:
    """Read the named places of each hex of an extraction of map locations.

    Towns and the other names of the map alike: the game names a spot after the
    nearest of any of them.

    Args:
        path (Path): The JSON written by fs-assets.

    Returns:
        dict[str, list[MapLocationEntry]]: The places of each hex, by its code, both
            sorted.

    Raises:
        ValueError: If the file is not an extraction of map locations, or a hex has
            no place.
    """
    locations = MapLocations.model_validate_json(path.read_bytes())
    empty = sorted(hex_code for hex_code, entries in locations.hexes.items() if not entries)
    if empty:
        raise ValueError(f"The extraction has no place for: {', '.join(empty)}")
    return {
        hex_code: sorted(entries, key=lambda entry: entry.name)
        for hex_code, entries in sorted(locations.hexes.items())
    }


def _location_line(entry: MapLocationEntry) -> str:
    """Write one place of the module.

    Args:
        entry (MapLocationEntry): The place.

    Returns:
        str: Its line, with its name as a Python string.
    """
    name = json.dumps(entry.name, ensure_ascii=False)
    return f"        ({name}, {entry.x:.6f}, {entry.y:.6f}),\n"


def render_location_table(locations: dict[str, list[MapLocationEntry]]) -> str:
    """Write the module that holds the named places.

    Args:
        locations (dict[str, list[MapLocationEntry]]): The places of each hex, by its
            code.

    Returns:
        str: The source of the module, already formatted.
    """
    lines = [_HEADER]
    for hex_code, entries in locations.items():
        lines.append(f"    {json.dumps(hex_code.lower())}: (\n")
        lines.extend(_location_line(entry) for entry in entries)
        lines.append("    ),\n")
    lines.append("}\n")
    return "".join(lines)


def import_map_locations(map_locations: Path, output: Path) -> MapLocationsReport:
    """Write the named places of each hex into the module of the application.

    Args:
        map_locations (Path): The JSON written by fs-assets.
        output (Path): The module to write.

    Returns:
        MapLocationsReport: What was written.
    """
    locations = read_locations(map_locations)
    output.write_text(render_location_table(locations), encoding="utf-8")
    known = {member.value.lower() for member in Hex}
    return MapLocationsReport(
        hexes=len(locations),
        locations=sum(len(entries) for entries in locations.values()),
        not_in_enum=[hex_code for hex_code in locations if hex_code.lower() not in known],
    )
